-- 0048 — норматив совокупных удержаний площадки в справочнике.
--
-- В прототипе доля агентского вознаграждения не вводится, а ВЫВОДИТСЯ: строка 85
-- считает `=43%-AR83-AR89-AR91-AR101-AR103`, то есть из норматива площадки
-- вычитаются доли комиссии, транспортной и складской логистики, штрафов и прочих
-- удержаний, а остаток и есть агентское. Нормативы зашиты прямо в формулы:
-- Wildberries 43 %, Lamoda 34 %, Ozon 35 %, Yandex Market 32 %.
--
-- Держим их данными, а не в коде: норматив меняется по договору с площадкой, и
-- появление новой площадки не должно требовать релиза. Владелец норматива и
-- регламент пересмотра — вопрос 31 (docs/reports/plans/open-questions.md); до
-- ответа значения взяты из файла и правятся в справочнике.
--
-- Площадки без норматива (мелкие МП, KZ/UZ) остаются без поля: там доля
-- агентского вводится как обычная статья.

UPDATE plans_directory_row r
   SET payload_json = jsonb_set(r.payload_json, '{norm_share}', to_jsonb(v.norm))
  FROM plans_directory d,
       (VALUES (335, 0.43), (336, 0.34), (337, 0.35), (954, 0.32)) AS v(cfo, norm)
 WHERE d.id = r.directory_id
   AND d.code = 'dir_marketplace'
   AND r.payload_json->>'code_cfo' = v.cfo::text;
