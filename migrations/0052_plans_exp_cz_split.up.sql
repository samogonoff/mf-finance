-- Ответ 43 (10.09.2026): центры затрат — ОТДЕЛЬНАЯ форма со своим ТЗ.
--
-- Код TPL-CFO-EXP носили два шаблона задания сразу: «Затраты ЦП» на этапе 1.5 и
-- «Затраты ЦЗ» на этапе 2.3. Форма построена по ТЗ этапа 1.5 (центры прибыли), и
-- задание 2.3 вело бы человека в чужой комплект. Разводим коды: TPL-CFO-EXP
-- остаётся за 1.5, у 2.3 — свой TPL-CZ-EXP.
--
-- Центры затрат — это ЦЗ 31, 32, 33, 34, 37, у каждого свои реестры, которых в
-- форме 1.5 нет. Формы под этот код пока не существует: у задания 2.3 просто не
-- будет кнопки «Форма», как и до сих пор.

UPDATE pl_task_template
   SET form_code = 'TPL-CZ-EXP'
 WHERE stage_code = '2.3' AND form_code = 'TPL-CFO-EXP';

-- Уже сгенерированные задания периода — тоже: иначе старые периоды продолжат
-- показывать ссылку на форму центров прибыли.
UPDATE pl_task
   SET form_code = 'TPL-CZ-EXP'
 WHERE stage_code = '2.3' AND form_code = 'TPL-CFO-EXP';
