--
-- Правки ТЗ 02.09.2026: Розница §15/§16, МП §15.
--
-- §16: колонка «Компания» есть ТОЛЬКО в FormToLoaTaktTarget и
-- VFORMTOLOADTAKTTARGET — в плане и факте её нет. Наша тактика пишется именно
-- туда, значит Компанию писать ОБЯЗАНЫ. §15: пишется реальный УНП, а не
-- фиктивный код. Песочница приёмника (0041) обязана вести себя как приёмник,
-- поэтому колонка добавляется и в неё.
--
-- МП §15: «площадки уже есть в приёмниках, ограничение dry-run снимается».
-- Набор КодPL подтверждён: 1006, 1022, 1045, 1046, 1106, 1122, 2006, 2106, 5006,
-- 6006, 6106, 7006, 8006, 9006, 9106 — пятнадцать значений, и состав зависит от
-- ЦФО (у 335/336/337/954 все 15, у 250 только восемь). Поэтому включаются
-- правила тех строк формы, у которых КодPL однозначен; остальные остаются
-- выключенными с пометкой, а не «включим и посмотрим».

