-- Публикация формы этапа 1.5 (ТЗ §10, ответы 34 и 11 от 10.09.2026).
--
-- Публикация ЦФО 250 переехала из формы продаж в форму 1.5: там она собирает
-- вместе реестр общих затрат МП, статьи 51 и 52 реестра логистики и строки ИТ с
-- признаком «перенести на ЦФО 250». В форме МП те же статьи остались расчётным
-- индикатором PL продаж и в приёмник затрат не пишут — иначе под одним
-- логическим ключом оказались бы два источника, и приёмник получил бы двойные
-- затраты.
--
-- Поэтому включаем публикацию на шаге утверждения формы 1.5: если оставить её
-- выключенной, после снятия публикации с формы продаж ЦФО 250 не публиковал бы
-- НИКТО. Фактическая запись всё равно за PLANS_PUBLISH_ENABLED: без него
-- утверждение делает dry-run.

UPDATE plans_form_route
   SET publish_on_approve = TRUE
 WHERE form_code = 'TPL-CFO-EXP' AND step_code = '1.4';

-- Правило маппинга для затрат формы 1.5. Приёмник и параметр берутся из данных,
-- как у остальных форм: имя таблицы в коде не зашивается.
INSERT INTO publish_mapping (form_code, block_type, country, param_name, target_table, enabled, note)
SELECT 'TPL-CFO-EXP', 'exp', '', 'ЗАТРАТЫ', 'Budgeting.dbo.FormToLoadPlan', FALSE,
       'Этап 1.5. Выключено до сверки с BI: сначала dry-run, затем песочница, затем запись.'
 WHERE NOT EXISTS (
        SELECT 1 FROM publish_mapping
         WHERE form_code = 'TPL-CFO-EXP' AND block_type = 'exp' AND country = '');
