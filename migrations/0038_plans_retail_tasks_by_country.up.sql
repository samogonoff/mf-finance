-- 0038 — задание «Товарооборот розницы» разбивается по странам.
--
-- Было: один шаблон на всю розницу (`cfo_filter = {"group_cfo1":"Розница"}`) →
-- одно задание на 211 ЦФО всех четырёх стран. А форм розницы ЧЕТЫРЕ — по одной
-- на страну (ТЗ §2.0: «экземпляр формы = (страна, период)… возврат по одной
-- стране не должен блокировать остальные»). Из-за этого задание нельзя было
-- связать с формой: непонятно, какую из четырёх открывать, и в интерфейсе у
-- розницы просто не было кнопки перехода в форму — данные вносить было негде.
--
-- Стало: четыре задания, каждое ссылается ровно на одну карточку страны.
-- Заодно это чинит и процесс: возврат по РФ больше не трогает РБ.

