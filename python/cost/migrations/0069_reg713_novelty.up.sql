-- 0069 — обоснование вида согласования в карточке 713 (задача Б24 666631, Стельмачёнок)
--
-- Исполком для карточки 713 требует обоснования по виду согласования — бренды
-- уже заполняют эти данные столбцами в расчётном файле, теперь они появляются
-- и в web-карточке:
--   • новинка        → в чём именно новизна (новый вид/состав сырья, усложнённая
--                      конструкция и т.п.) + планируемый объём реализации
--                      на внутренний рынок;
--   • повышение цены → производитель-«конкурент» и его розничная цена
--                      («розничная цена аналога других производителей»).
--
-- Поля необязательны на уровне БД: обязательность проверяется сервисом только
-- в момент сохранения РЕШЕНИЯ исполкома (см. save_card в app/reg713.py) —
-- отметка «на согласование» и заполнение аналога блокироваться не должны.

ALTER TABLE cost_reg713
    ADD COLUMN IF NOT EXISTS novelty_comment   TEXT,
    ADD COLUMN IF NOT EXISTS planned_volume    NUMERIC(14, 2),
    ADD COLUMN IF NOT EXISTS competitor_name   TEXT,
    ADD COLUMN IF NOT EXISTS competitor_retail NUMERIC(14, 2);
