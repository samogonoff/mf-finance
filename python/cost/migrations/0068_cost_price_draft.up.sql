-- 0068 — черновик несохранённых цен бренд-менеджера (просьба Б24 от 14.10.2026, Сапега)
--
-- Введённые, но не отправленные кнопкой «Сохранить изменения» цены жили только
-- в памяти вкладки: перезагрузка браузера или новый заход стирали их начисто.
-- Черновик бренд-менеджер расценивает по частям и сохраняет в конце — между
-- этими заходами ввод обязан доживать. Храним его на сервере по ключу
-- (пользователь + калькуляция): переживает перезагрузку, закрытие браузера и
-- смену устройства — как настройки таблицы из 0041.
--
-- Границы (важно, чтобы не повторить инцидент 18.09.2026 с pending-заявками):
--   • строка черновика НИКОГДА не попадает в выдачу /aggregated, не влияет на
--     cost_price_pending, согласование ПЭО, блокировки строк и серверные
--     фильтры — это личная рабочая копия, а не заявка;
--   • запись только дополняет/перезаписывает свой ключ (upsert), удаление —
--     только явное (успешное «Сохранить изменения» или «Сбросить введённые
--     значения»);
--   • срок жизни 30 дней: при каждой записи черновики старше вычищаются, чтобы
--     ключи давно вышедших калькуляций не копились вечно.

CREATE TABLE IF NOT EXISTS cost_price_draft (
    email       TEXT NOT NULL,
    -- Ключ калькуляции = «Модель|Артикул|PLAN_ID|Признак» по фронтендному
    -- calcRowKey (разделитель U+0001). Шире ключа заявки ПЭО не делает: цена в
    -- разделе ставится на ту же четверку.
    row_key     TEXT NOT NULL,
    -- {row: {...снимок строки выдачи...}, markup, rf, kz, uz} — схему держит
    -- фронт, сервер только ограничивает размер (см. app/routes.py).
    snapshot    JSONB NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (email, row_key)
);

COMMENT ON TABLE cost_price_draft IS
    'Личный черновик несохранённого ввода цен: строка на (пользователь, калькуляция). Не заявка ПЭО — в выдачу и наложение не входит.';
