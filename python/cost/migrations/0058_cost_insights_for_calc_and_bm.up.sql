-- 0058 — «Разбор ИИ» и чат с агентом доступны калькулятору и бренд-менеджеру.
--
-- Миграция 0045 выдала право cost:insights только «ПЭО» и «Full Admin», и на
-- дашбордах у остальных ролей блок разбора и чат с агентом не показывались
-- вовсе (CostChartInsight.vue: available = enabled && can('cost:insights')).
-- Заказчик 22.09.2026: доступ нужен и калькулятору, и бренд-менеджеру.
-- В модель уходят только агрегаты с графиков, построчная себестоимость и
-- артикулы туда не попадают — расширение круга ролей данных не раскрывает.

UPDATE cost_roles
   SET permissions = permissions || '["cost:insights"]'::jsonb,
       updated_at = now()
 WHERE name IN ('Калькулятор', 'Бренд-менеджер')
   AND NOT permissions @> '["cost:insights"]'::jsonb;
