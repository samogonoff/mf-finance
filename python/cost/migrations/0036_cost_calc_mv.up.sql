-- Объём выпуска в кэше + материализованная витрина калькуляций.
--
-- ЧАСТЬ 1. ОБЪЁМ ВЫПУСКА
-- ======================
-- Колонка [выпуск шт] есть в источнике ([Checks].[dbo].[CostHistory]), но не
-- попадала в локальный кэш: _producer делает SELECT * и пересекает результат с
-- CACHE_COLUMNS, а её в списке не было. Добавляем колонку сюда и имя в
-- CACHE_COLUMNS — дальше она наполнится сама на следующем refresh кэша.
--
-- Зачем: без объёма нельзя посчитать показатели «выпуска» (маржинальность и
-- рентабельность выпуска). Среднее по изделиям — не то же самое: модель с 80%
-- маржи и тиражом 10 штук весит столько же, сколько хит с тиражом миллион.
-- Корректно это Σ(наценка × объём) / Σ(отпускная × объём).
--
-- ВНИМАНИЕ: до первого refresh кэша колонка будет NULL, и взвешенные показатели
-- тоже. Это ожидаемо, а не поломка.

ALTER TABLE cost_data_cache
    ADD COLUMN IF NOT EXISTS "выпуск шт" NUMERIC;

-- ЧАСТЬ 2. ВИТРИНА КАЛЬКУЛЯЦИЙ
-- ============================
-- cost_data_cache — построчная детализация материалов и операций: ~1 млн строк
-- на ~87 тыс. калькуляций, в среднем 11-12 строк на калькуляцию. Любая
-- аналитика начинается со свёртки до калькуляции, и свёртка стоит ~3 секунды:
-- полный parallel seq scan плюс две сортировки с выгрузкой на диск по 24 МБ
-- (EXPLAIN ANALYZE, 12.08.2026).
--
-- Дашборд из 4 чартов и 6 фильтров делает эту свёртку заново на КАЖДЫЙ виджет —
-- двадцать с лишним полных сканов на одно открытие, по живой БД раздела. Это
-- уже приводило к таймаутам в браузере. Витрина считает свёртку один раз после
-- обновления кэша.
--
-- ГРАНУЛЯРНОСТЬ
-- =============
-- Одна строка = одна калькуляция. Натуральный ключ:
--   Модель + Артикул + Признак калькуляции + PLAN_ID + дата расчета
--   + Номер задания производства
--
-- Номер задания входит обязательно: подтверждено заказчиком 12.08.2026 — одна
-- модель в разных заданиях производства имеет разную себестоимость. Без него
-- себестоимость «плавает» внутри ключа в 12 396 случаях из 28 340, а SUM по
-- сырой таблице завышает результат примерно в 11 раз.
--
-- ЧТО НАМЕРЕННО НЕ ВОШЛО
-- ======================
-- Уровень материалов: Наименование, артикул материала, свойство1-3, Норма,
-- цена материала, Материал/операция/декор(призн), Декоры наименование. Они
-- живут на строке материала, а не на калькуляции. Если понадобится фильтровать
-- калькуляции по материалу, нужен отдельный объект связи калькуляция→материал.
--
-- Здесь также НЕТ аналитических суждений: ни отсечения выбросов, ни выбора
-- последней калькуляции на этапе. Это базовый слой фактов; логика — в запросах
-- и датасетах поверх него.
--
-- ИМЕНА ЛАТИНИЦЕЙ
-- ===============
-- В источнике имена русские, с пробелами и точками — их приходится всюду
-- цитировать, а Superset вдобавок блокирует запросы, где встречается слово
-- version. Здесь латиница: меньше трения и в SQL, и в BI.
--
-- ВАЛЮТА
-- ======
-- Колонки *_byn — белорусские рубли (курс к USD в fx_rate ≈ 3), несмотря на
-- «руб.» в исходных именах. В интерфейсе подписывать BYN, не RUB.

CREATE MATERIALIZED VIEW IF NOT EXISTS cost_calc_mv AS
SELECT
    -- Натуральный ключ. Отдаём как есть, включая NULL: PLAN_ID и номер задания
    -- местами не заполнены (по 2 строки на миллион), и подменять их пустой
    -- строкой значило бы склеить с реальными пустыми значениями.
    "Модель"                            AS model,
    "Артикул"                           AS articul,
    "Признак калькуляции"               AS calc_sign,
    "PLAN_ID"                           AS plan_id,
    "дата расчета"                      AS calc_date,
    "Номер задания производства"        AS zadanie,

    -- Суррогатный ключ для UNIQUE-индекса. Нужен, потому что REFRESH
    -- MATERIALIZED VIEW CONCURRENTLY требует уникального индекса, а составной
    -- по nullable-колонкам его не даёт: в UNIQUE два NULL считаются разными,
    -- и refresh упал бы на дубликатах.
    md5(
        coalesce("Модель", '')                     || E'\x01' ||
        coalesce("Артикул", '')                    || E'\x01' ||
        coalesce("Признак калькуляции", '')        || E'\x01' ||
        coalesce("PLAN_ID", '')                    || E'\x01' ||
        coalesce("дата расчета"::text, '')         || E'\x01' ||
        coalesce("Номер задания производства", '')
    )                                   AS calc_key,

    -- Измерения. Проверены на постоянство внутри ключа (87 043 ключа,
    -- расхождений ноль) — max() берёт единственное значение, а не произвольное.
    max("Бренд-менеджер")               AS brand_manager,
    max("Наименование модели")          AS model_name,
    max("Уровень цен")                  AS price_level,
    max("Страна пр-ва")                 AS country,
    max("Сезон")                        AS season,
    max("Level 01")                     AS level01,
    max("Level 02")                     AS level02,
    max("Level 03")                     AS level03,
    max("Level 04")                     AS level04,
    max("Level 05")                     AS level05,
    max("color")                        AS color,
    max("дата производства")            AS production_date,

    -- «Семья» постоянством НЕ обладает: расходится в 7 ключах из 87 043.
    -- Берём max() и помечаем такие строки флагом is_ambiguous — молча выбирать
    -- одно из двух значений и не сообщать об этом нельзя.
    max("Семья")                        AS family,

    -- Объём выпуска. Из [выпуск шт] источника. Предполагается постоянным внутри
    -- калькуляции (как остальные её атрибуты) — ПРОВЕРИТЬ на первых реальных
    -- данных: если окажется, что значение живёт на строке материала, max() здесь
    -- неверен и нужна сумма либо другая свёртка.
    max("выпуск шт")                    AS volume_pcs,

    -- Цены и себестоимость. Розничная и отпускная постоянны внутри ключа.
    max("Розничная цена по уровню, руб.")   AS retail_price_byn,
    max("Розничная цена по уровню, USD.")   AS retail_price_usd,
    max("Отпускная цена по уровню, руб")    AS wholesale_price_byn,
    max("Отпускная цена по уровню, USD.")   AS wholesale_price_usd,
    max("Себестоимость, руб.")              AS cost_byn,
    max("Себестоимость, USD.")              AS cost_usd,

    -- Составляющие себестоимости — основа «структуры себестоимости» на
    -- дашборде. «Пошив» расходится в тех же 7 ключах, что и «Семья».
    max("Основные материалы, руб.")         AS mat_main_byn,
    max("Основные материалы, USD.")         AS mat_main_usd,
    max("Вспомогательные материалы, руб.")  AS mat_aux_byn,
    max("Вспомогательные материалы, USD.")  AS mat_aux_usd,
    max("Пошив, руб.")                      AS sewing_byn,
    max("Пошив, USD.")                      AS sewing_usd,
    max("Раскрой, руб.")                    AS cutting_byn,
    max("Раскрой, USD.")                    AS cutting_usd,
    max("Декоры, руб.")                     AS decor_byn,
    max("Декоры, USD.")                     AS decor_usd,
    max("Вязание, руб.")                    AS knitting_byn,
    max("Вязание, USD.")                    AS knitting_usd,

    max("Курс на дату расчета")             AS fx_rate,
    max("Ставка НДС")                       AS vat_rate,
    max("Пошив, минуты")                    AS sewing_minutes,
    max("Раскрой, минуты")                  AS cutting_minutes,

    -- Сколько строк материалов свернулось в калькуляцию. Аномально малое число
    -- — признак неполной калькуляции.
    count(*)                                AS material_rows,

    -- TRUE, если внутри ключа разошлись «Семья» или «Пошив». Таких 14 из 87 043
    -- (0,016%): по 7 ключей на каждое поле, множества не пересекаются. Флаг
    -- существует, чтобы расхождение можно было увидеть и отфильтровать, а не
    -- чтобы оно растворилось в max().
    (count(DISTINCT "Семья") > 1 OR count(DISTINCT "Пошив, руб.") > 1)
                                            AS is_ambiguous
FROM cost_data_cache
GROUP BY
    "Модель", "Артикул", "Признак калькуляции",
    "PLAN_ID", "дата расчета", "Номер задания производства"
WITH DATA;

-- Обязателен для REFRESH ... CONCURRENTLY. Без CONCURRENTLY обновление берёт
-- ACCESS EXCLUSIVE на витрину, и читатели (дашборды) блокируются на пересчёт.
CREATE UNIQUE INDEX IF NOT EXISTS cost_calc_mv_key_idx
    ON cost_calc_mv (calc_key);

-- 87 тыс. строк сканируются быстро и без индексов, поэтому их минимум: только
-- то, по чему заведомо фильтруют дашборды. Остальные — по факту медленных
-- запросов, а не на всякий случай.
CREATE INDEX IF NOT EXISTS cost_calc_mv_sign_idx   ON cost_calc_mv (calc_sign);
CREATE INDEX IF NOT EXISTS cost_calc_mv_date_idx   ON cost_calc_mv (calc_date);
CREATE INDEX IF NOT EXISTS cost_calc_mv_model_idx  ON cost_calc_mv (model, articul);

COMMENT ON MATERIALIZED VIEW cost_calc_mv IS
    'Калькуляции (свёртка cost_data_cache до натурального ключа). Обновляется '
    'после refresh кэша — см. set_cache_completed() в app/db.py. Суммы *_byn '
    'в белорусских рублях. volume_pcs пуст до первого refresh после миграции.';
