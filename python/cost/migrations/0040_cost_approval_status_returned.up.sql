-- 0040 — статус ПЭО «возвращено на корректировку»
--
-- Возврат калькуляции бренд-менеджеру на исправление — это отдельное состояние,
-- а не «отклонено». Отклонение означает «цена не годится и решение принято»,
-- возврат — «жду исправленную цену». До этой миграции оба случая ложились в
-- 'rejected', и в таблице их было не различить.
--
-- Ставится в двух местах (решение заказчика 25.08.2026):
--   • возврат из модалки согласования цен («Отклонить выбранные»);
--   • переоткрытие калькуляции, уже записанной в DWH (миграция 0039).
--
-- В обоих случаях цена, введённая бренд-менеджером, СОХРАНЯЕТСЯ: раньше
-- reset_price_fields обнулял поля цен и удалял запись из cost_price_pending,
-- из-за чего пользователь получал пустое поле и вводил цену заново.

ALTER TABLE cost_calc_approvals DROP CONSTRAINT IF EXISTS cost_calc_approvals_status_check;
ALTER TABLE cost_calc_approvals ADD CONSTRAINT cost_calc_approvals_status_check
    CHECK (status IN ('pending', 'approved', 'rejected', 'returned'));
