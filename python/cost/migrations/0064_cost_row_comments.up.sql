-- 0064 — живые комментарии к строке калькуляции (задача Б24 664394)
--
-- Инцидент: калькулятор отметила замену артикула, написала комментарий в строке
-- новой калькуляции — и «комментарий не сохранился». Причина не в потере записи,
-- а в том, что комментарий умел сохраняться ТОЛЬКО вместе с заявкой на цену:
-- строка без розничной цены («прочерк») заявкой не становится (просьба
-- заказчика 18.09.2026 — заявка с нулевой ценой вредна), и вместе с ней молча
-- отбрасывался комментарий. Он жил в памяти браузера до первой перезагрузки.
--
-- Решение: комментарий становится самостоятельной сущностью, а не попутчиком
-- заявки. Пишется сразу при вводе (отдельный эндпоинт, не «Сохранить
-- изменения»), лежит в своей таблице и накладывается на выдачу всем
-- пользователям. Заявка на цену по-прежнему несёт свой снимок комментария в
-- cost_price_pending → CostHistory_Changes — цикл согласования не меняется.
--
-- Ключ тот же, что у заявки (uq_pending_row, миграция 0005): модель, артикул,
-- план, признак калькуляции. Пустые части хранятся как '' (не NULL), чтобы
-- UNIQUE работал как ключ (урок миграции 0023).

CREATE TABLE IF NOT EXISTS cost_row_comments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Модель"              TEXT NOT NULL,
    "Артикул"             TEXT NOT NULL,
    "PLAN_ID"             TEXT NOT NULL DEFAULT '',
    "Признак калькуляции" TEXT NOT NULL DEFAULT '',
    "Комментарий"         TEXT NOT NULL DEFAULT '',
    updated_by            TEXT,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_row_comment UNIQUE ("Модель", "Артикул", "PLAN_ID", "Признак калькуляции")
);

CREATE INDEX IF NOT EXISTS idx_row_comment_model
    ON cost_row_comments ("Модель", "Артикул");

COMMENT ON TABLE cost_row_comments IS
    'Живые комментарии к строке калькуляции (задача 664394): пишутся сразу при вводе, видны всем пользователям, не зависят от цикла заявка/согласование. Ключ как у cost_price_pending (uq_pending_row).';
