-- 0051 — подключение к языковой модели настраивается из админки, а не деплоем
--
-- До сих пор провайдер, ключ и модель жили только в `python/cost/.env`, а на
-- проде — в CI-переменной ENV_FILE_COST → docker config → /var/www/cost/.env.
-- Смена модели там стоила полного деплоя стека, и это оказалось неприемлемо:
-- за один день 02.09.2026 модель меняли четыре раза (glm-5 → deepseek-v4-flash,
-- потом протокол, потом reasoning_effort), а провайдеры нестабильны — у
-- opencode zen на наших глазах разом отвалились Claude, GPT и Gemini. Когда
-- модель ломается в проде, переключиться нужно за минуту.
--
-- ПОЧЕМУ НЕ ПРАВИТЬ CI-ПЕРЕМЕННУЮ ИЗ ПРИЛОЖЕНИЯ
-- =============================================
-- Технически это потребовало бы держать в контейнере токен GitLab API с правом
-- менять переменные проекта — риск куда больший, чем решаемая задача. И даже
-- тогда значение не долетело бы до работающего сервиса: контейнер получает
-- .env из `docker config`, а тот в Swarm неизменяемый, новое значение
-- появляется только с новым деплоем. То есть смена модели всё равно стоила бы
-- деплоя, и затея теряет смысл.
--
-- ПРИОРИТЕТ ИСТОЧНИКОВ
-- ====================
-- Значение из этой таблицы ПЕРЕКРЫВАЕТ переменную окружения, пустое поле
-- означает «взять из .env». Отсюда: dev продолжает работать по `.env` как
-- раньше, ничего не настраивая, а прод настраивается через интерфейс и
-- CI-переменную можно вообще не трогать.
--
-- Одна строка на весь раздел (id = 1 с CHECK, как в cost_cache_status): это
-- настройка контура, а не пользователя.
--
-- ПРО КЛЮЧ. Лежит в открытом виде и попадает в бэкапы БД. Шифровать смысла
-- мало: ключ шифрования пришлось бы держать в том же .env, к которому мы и
-- пытаемся не возвращаться. Доступ к БД раздела и без того равен доступу ко
-- всей себестоимости, так что новой поверхности почти не добавляется. Наружу
-- ключ отдаётся только маской (последние 4 символа), в логи не пишется.

CREATE TABLE IF NOT EXISTS cost_llm_settings (
    id            INTEGER     PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    -- Пустая строка — «не задано, брать из окружения». NULL не используем,
    -- чтобы не различать в коде два вида «пусто».
    enabled       BOOLEAN,
    api_base      TEXT        NOT NULL DEFAULT '',
    api_key       TEXT        NOT NULL DEFAULT '',
    model         TEXT        NOT NULL DEFAULT '',
    -- none | low | medium | high. none обязателен по умолчанию: «думающие»
    -- модели тратят на рассуждения токены сверх max_tokens и упираются в
    -- таймаут (замер 02.09.2026: 17–127 с против 2–3 с с none).
    reasoning     TEXT        NOT NULL DEFAULT '',
    timeout_s     INTEGER,
    -- Бюджет времени на одно углублённое исследование, секунды.
    agent_budget_s INTEGER,
    updated_by    TEXT        NOT NULL DEFAULT '',
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Строка создаётся сразу пустой: код тогда не различает «таблицы нет»,
-- «строки нет» и «поля пустые» — везде фолбэк на окружение.
INSERT INTO cost_llm_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

COMMENT ON TABLE cost_llm_settings IS
    'Подключение к языковой модели («Разбор ИИ» и исследования), настраивается на /cost/admin/llm. Значения перекрывают COST_LLM_* из .env; пустое поле = брать из окружения. Одна строка на контур.';

COMMENT ON COLUMN cost_llm_settings.api_key IS
    'Ключ провайдера в открытом виде (попадает в бэкапы БД). Наружу отдаётся только маской, в логи не пишется.';

-- Право на настройку. Отдельно от cost:admin: управление ролями и управление
-- внешним провайдером с оплачиваемым ключом — разные полномочия, и второе
-- может понадобиться выдать без первого (или наоборот). Пока выдаётся тем же
-- ролям, что и админство.
UPDATE cost_roles
   SET permissions = permissions || '["cost:llm_admin"]'::jsonb
 WHERE name IN ('Full Admin')
   AND NOT permissions @> '["cost:llm_admin"]'::jsonb;
