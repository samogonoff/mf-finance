-- 0044 — индекс по номеру плана в кэше расчётов
--
-- Из аудита логов ELK за 14 дней (28.08.2026): POST /submit-calculation-draft
-- в норме отвечает мгновенно (p50 ≈ 0), но каждый 10-й запрос висит 90–260
-- секунд, а 24.08 в 08:19 разом зависли 30+ запросов и разрешились в одну
-- секунду — так выглядит ожидание блокировки, а не медленный запрос.
--
-- Источник блокировки — применение набора цен по плану (_rebuild_plan_cache и
-- _apply_plan_price_set_to_cache). Внутри ОДНОЙ транзакции оно четыре раза
-- проходит cost_data_cache по условию trim(COALESCE("PLAN_ID", '')) = $1:
-- DELETE строк плана, UPDATE коэффициентов, два UPDATE цен набора. Индекса по
-- этому выражению не было, каждый проход — Parallel Seq Scan по миллиону строк
-- (на dev 0,3 с и 343 355 отброшенных строк на проход; на проде под нагрузкой
-- кратно дольше). Строки плана остаются заблокированными до конца транзакции,
-- и сабмит калькуляции того же плана ждёт её целиком. Применение набора
-- plan-price-sets/67/apply шло 187–236 секунд.
--
-- Индекс — по тому же выражению, что в запросах, иначе планировщик его не
-- возьмёт. Строки без плана (PLAN_ID NULL или пустой — 32 709 на dev) в индекс
-- попадают как '' — это нормально, по ним никто не ищет.
--
-- CONCURRENTLY нельзя: миграции идут в транзакции golang-migrate. Обычный
-- CREATE INDEX на миллион строк — секунды, но он держит ShareLock на таблицу,
-- поэтому накат стоит делать не в разгар рабочего дня.

CREATE INDEX IF NOT EXISTS idx_cache_plan_id_trim
    ON cost_data_cache ((trim(COALESCE("PLAN_ID", ''))));

-- Та же беда у копий калькуляций (0043) впереди не грозит — там таблица
-- маленькая, — но выражение то же, и индекс уже есть (idx_cost_manual_calc_key).

COMMENT ON INDEX idx_cache_plan_id_trim IS
    'Поиск строк плана в кэше: применение наборов цен и правки материалов по плану. Без него — seq scan по миллиону строк и блокировки на минуты.';
