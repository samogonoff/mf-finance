-- 0031 — коэффициент связи «Норма × цена» с реальной стоимостью статьи.
--
-- Проблема. _recalc_cost_buckets при создании/сохранении версии перезаписывал
-- денежный бакет произведением Норма × цена материала. Но в источнике
-- (Checks.CostHistory) бакет НЕ равен этому произведению по двум причинам:
--
--   а) цена материала имеет тип money(19,4), т.е. сама округлена до 4 знаков,
--      а бакет посчитан из неокруглённой цены. Пример: бакет 0.048079 при
--      Норма 92.5 даёт цену 0.00051977, а вью показывает 0.0005.
--      Медиана отношения бакет/(норма×цена) — 0.9988.
--
--   б) примерно у четверти строк бакет меньше произведения в разы (25-й
--      процентиль отношения — 0.1741, 5-й — 0.0002). Пример: Норма 1.05,
--      цена 2.75, а бакет 0.000686. Доменная причина (единицы измерения либо
--      разнесение стоимости) из данных не выводится.
--
-- Итог: сохранение версии искажало себестоимость — тем сильнее, чем дальше
-- коэффициент от единицы. Замер на источнике (~986 тыс. строк за 3 месяца):
-- медиана отношения стоимость/(норма×цена) — 0.9988, 75-й процентиль 1.0003,
-- но 25-й — 0.1741, а 5-й — 0.0002. То есть у четверти строк стоимость
-- завышалась в разы. Разовый пересчёт уже сохранённых версий на dev-данных
-- сдвинул стоимость материалов на -13.66 руб по 208 строкам в 44 версиях,
-- максимум по одной версии -1.95 руб.
--
-- Решение. Храним коэффициент factor = бакет / (Норма × цена), посчитанный
-- один раз при загрузке из источника, и всегда считаем бакет как
-- Норма × цена × factor. Тогда:
--   • без правок бакет воспроизводит источник (обе причины поглощены factor'ом);
--   • при правке цены/нормы стоимость меняется пропорционально, а скрытый
--     коэффициент источника сохраняется.
--
-- NULL = «коэффициент неизвестен, считать 1». Так ведут себя операционные
-- строки (пошив/раскрой/вязание): у них в источнике нет цены, а _derive_norm_price
-- выводит Норма=минуты, цена=стоимость/минуты, т.е. произведение и так точно
-- равно стоимости и коэффициент не нужен.
--
-- Точность 12 знаков выбрана осознанно: при Норма×цена до ~1e4 ошибка
-- восстановления бакета не превышает 1e-8, что заведомо ниже 6 знаков,
-- с которыми бакеты хранятся после миграции 0030.
--
-- ВАЖНО: миграция только добавляет колонки. Для cost_data_cache они
-- заполняются автоматически при следующей загрузке из источника
-- (load_cost_data_to_cache). Для УЖЕ сохранённых строк версий нужен разовый
-- пересчёт скриптом python/cost/scripts/recalc_version_buckets.py — из кэша их
-- восстановить нельзя, потому что кэш по ключам с активными версиями содержит
-- строки самой версии, а не исходные данные.

ALTER TABLE cost_data_cache
    ADD COLUMN IF NOT EXISTS cost_factor_rub numeric(20,12),
    ADD COLUMN IF NOT EXISTS cost_factor_usd numeric(20,12);

ALTER TABLE cost_calc_version_rows
    ADD COLUMN IF NOT EXISTS cost_factor_rub numeric(20,12),
    ADD COLUMN IF NOT EXISTS cost_factor_usd numeric(20,12);
