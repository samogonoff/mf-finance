-- Теряются кэш (следующие разборы будут пересчитаны за деньги) и история
-- обращений к модели. Сам блок «Разбор ИИ» после откатa продолжает работать:
-- app/insights.py считает факты и зовёт модель, не обращаясь к этой таблице, —
-- пропадают только кэширование и аудит.

DROP TABLE IF EXISTS cost_insight_runs;

-- Право снимаем со всех ролей: без эндпоинта оно бессмысленно и только мусорит
-- в списке прав администратора.
UPDATE cost_roles
   SET permissions = permissions - 'cost:insights'
 WHERE permissions @> '["cost:insights"]'::jsonb;
