-- 0043 — калькуляция с другим признаком: копия расчёта, оригинал не меняется
--
-- Пункт 1 «Списка доработок» (Апанасёнок О.): «на этапе экономистов
-- предоставить возможность менять признак калькуляции (для перемаркировок и
-- расценки ЧНИ)». Заказчик уточнил 27.08.2026, что менять признак у исходной
-- калькуляции не нужно: исходная остаётся исходной, а появляется НОВАЯ
-- калькуляция с другим признаком, и дальше она живёт обычным циклом — правки
-- материалов, цена бренд-менеджера, согласование ПЭО, запись в DWH. На практике
-- ожидается переход ПКПСС -> ПФКСС.
--
-- Почему отдельная таблица, а не правка cost_data_cache: кэш при обновлении
-- пересоздаётся целиком (TRUNCATE + переимпорт из источника либо DELETE по
-- дате), поэтому любая наша строка в нём была бы стёрта следующим обновлением.
--
-- Почему копия, а не ссылка на исходные строки: по решению заказчика копия —
-- самостоятельная калькуляция со своими цифрами, её правят и согласовывают
-- независимо, и пересчёт исходной в источнике не должен её менять.
--
-- Структура повторяет cost_data_cache один в один (LIKE), потому что строка
-- кэша — это построчная детализация калькуляции (материал, операция, декор), и
-- копия калькуляции есть копия всех её строк. Совпадение структуры позволяет
-- читать оба источника одним представлением cost_data_all, не переписывая
-- агрегацию, фильтры и детализацию.

CREATE TABLE IF NOT EXISTS cost_manual_calc (LIKE cost_data_cache);

-- id из LIKE приходит без последовательности — даём свою. Через DO, потому что
-- ADD GENERATED не имеет IF NOT EXISTS, а миграции в проекте обязаны
-- переприменяться без ошибок (см. swarm/migrate.sh: после сбоя накат повторяется).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'cost_manual_calc'
           AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE cost_manual_calc ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

ALTER TABLE cost_manual_calc
    ADD COLUMN IF NOT EXISTS batch_id          UUID        NOT NULL,
    ADD COLUMN IF NOT EXISTS source_calc_sign  TEXT        NOT NULL,
    ADD COLUMN IF NOT EXISTS source_task       TEXT,
    ADD COLUMN IF NOT EXISTS created_by        TEXT        NOT NULL,
    ADD COLUMN IF NOT EXISTS created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN IF NOT EXISTS reason            TEXT;

-- batch_id — одна операция создания. Удаление идёт пакетом: калькуляция без
-- части своих материалов смысла не имеет.
CREATE INDEX IF NOT EXISTS idx_cost_manual_calc_batch ON cost_manual_calc (batch_id);
CREATE INDEX IF NOT EXISTS idx_cost_manual_calc_key ON cost_manual_calc (
    (trim("Модель")), (trim("Артикул")),
    (trim(COALESCE("PLAN_ID", ''))), (trim(COALESCE("Признак калькуляции", '')))
);
CREATE INDEX IF NOT EXISTS idx_cost_manual_calc_created ON cost_manual_calc (created_at DESC);

COMMENT ON TABLE cost_manual_calc IS
    'Калькуляции, созданные в приложении как копия расчёта с другим признаком (пункт 1 «Списка доработок»). Структура совпадает с cost_data_cache; читаются вместе через cost_data_all.';

