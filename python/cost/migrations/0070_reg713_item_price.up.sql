--
-- Бренд-менеджер в карточке согласования выбирает «Розничную наценку» — как в
-- главной таблице: выбор уровня фиксирует розницу (PRICE_TYPE3) и опт
-- (PRICE_TYPE1) изделия. Снимок хранится в карточке:
--   • исполком видел именно эти цифры (та же логика, что у цен аналога);
--   • после «согласовано» главная таблица показывает ПФКСС-строкам пары ровно
--     эту цену, пока карточку не перевыпустят (routes.py, наложение перед
--     lock-state; правку цены тогда блокирует _reg713_lock — Б24 669728).
--
-- Поля необязательны: пустой снимок — цены изделия считаются по общим правилам
-- (последняя калькуляция → DWH → плановая), как раньше.

