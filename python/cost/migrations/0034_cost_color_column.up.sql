-- 0034 — цвет модели из источника на главной странице.
--
-- Поле [color] есть в [Checks].[dbo].[CostHistory] (это базовая таблица, не вью —
-- проверено через sys.objects), но в кэш не переносилось.
--
-- Цвет постоянен в рамках производственного задания: проверено на данных за
-- 3 месяца — 85 583 группы (модель, артикул, признак, план, задание), у ВСЕХ
-- ровно одно значение цвета, максимум 1. Поэтому поле безопасно добавить в
-- AGG_GROUP_FIELDS: агрегация от него не размножится, количество строк на
-- главной не изменится.
--
-- Значение заполнено далеко не везде: за те же 3 месяца NULL у 586 832 строк,
-- пустая строка у 390 147, реальные цвета («черный», «белый», «жемчуг»,
-- «мишки и сердца на молочном») — у остальных. Пустая колонка в UI — норма.
--
-- В источнике тип с хвостовыми пробелами, но _convert_mssql_row тримит все
-- текстовые поля при загрузке, так что в кэш попадает уже очищенное значение.
--
-- Колонка добавляется и в cost_calc_version_rows: эта таблица зеркалит
-- CACHE_COLUMNS, и без неё сохранение версии падало бы на несовпадении списка
-- колонок.

ALTER TABLE cost_data_cache
    ADD COLUMN IF NOT EXISTS color text;

ALTER TABLE cost_calc_version_rows
    ADD COLUMN IF NOT EXISTS color text;
