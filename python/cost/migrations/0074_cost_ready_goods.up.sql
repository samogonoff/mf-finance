-- 0074 · Сторонняя готовая продукция (ГП) в дашборде «Маржа выпуска».
--
-- ЗАЧЕМ
-- =====
-- Отчёт заказчика «Маржа выпускаТрикотаж» (Power BI) собран из ДВУХ источников:
-- «Выпуск из Лисы» (наш cost_calc_mv, только ФКСС) и «Поступление товара
-- стороннего» — товар, который не производили, а КУПИЛИ и перепродали. Второго
-- блока у нас не было вовсе: дашборд показывал маржу только собственного
-- производства, и его маржинальность расходилась с PBIX на несколько пунктов.
--
-- В PBIX оба блока склеены в одну таблицу (Table.Combine), а строка помечена
-- колонкой «ГП»: «Собственное» у выпуска, «ГП» у поступления. Здесь это делает
-- переключатель режима в дашборде (app/margin.py, GP_MODES), а данные блока
-- лежат отдельной таблицей: источник другой, обновляется отдельно, и в витрину
-- cost_calc_mv ему нельзя — витрина про калькуляции, а тут калькуляций нет.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ CTE ПОВЕРХ GPARTNER
-- ==================================================
-- Запрос к Gpartner.dbo.prix_modeli с джойнами doc_modeli/s_modeli/plan_proizv
-- идёт по внешней базе за VPN: секунды и недоступность при каждом открытии
-- страницы. Справочник синхронизируется при обновлении кэша
-- (sync_ready_goods, app/db.py), а дашборд читает локальную таблицу.
--
-- ГРАНУЛЯРНОСТЬ
-- =============
-- Месяц + документ поступления + модель + артикул. Месяц, а не дата: в PBIX
-- блок приводится к EOMONTH (месяц выпуска), и динамика по месяцам должна
-- складываться с выпуском. Документ — единица поступления: у одного документа
-- свой поставщик, план и закупщик; склеивать строки разных документов в одну
-- значило бы потерять, откуда пришла цена.
--
-- КЛАССИФИКАЦИЯ (Level 01…05, страна)
-- ===================================
-- У покупного товара своей иерархии нет, и взять её из витрины выпуска НЕЛЬЗЯ:
-- товар не производили, его нет в cost_calc_mv (по модели+артикулу совпадает
-- 1 пара из 2 503 — проверено 06.11.2026). Поэтому иерархия приходит из того же
-- места, что в отчёте Power BI: Checks.dbo.Groups (по MODEL_ID = s_modeli.ITEM_ID;
-- group1…group6 → Level 01…05 и шестой уровень, в дашборде не используется),
-- страна — s_modeli.COUNTRY. Сверено с PBIX по 14 181 строке ГП: распределение
-- по Level 01 и по стране совпадает (Женщинам 4 345 080 шт, Аксессуары
-- 1 092 944, Мужчинам 910 187; Китай 12 633 строки, Узбекистан 1 666).
--
-- Сезона у ГП в отчёте нет (S_MODELI_COLOR держит сезон на цвете модели, а не
-- на поступлении) — колонка остаётся пустой, как и в PBIX.
--
-- Метрики строки (сверено с M-запросом PBIX):
--   vol      = sum(pm.KOL)                          — количество, шт;
--   cost_byn = sum(pm.SUMMA_DOC - pm.SUMMA_NDS)     — закупка без НДС;
--   rev_byn  = sum(pm.KOL * sm.PRICE_UCH)           — по учётной (отпускной) цене.
--
-- cost_byn — то, что заплатили, а не расчётная себестоимость: у покупного
-- товара нет ни норм, ни минут пошива. Поэтому в дашборде у этих строк пусты
-- raw_*, sew_*, норматив/факт и норма маржинальности — там просто нечего
-- считать, а не «данных не хватило».
--
-- ПОКРЫТИЕ
-- ========
-- На 06.11.2026 источник отдаёт 2 738 строк на 14 663 документа-строки
-- (2025 — 762 строки, 1 975 518 шт; 2026 — 742 строки, 1 951 220 шт). Сверка с
-- эталоном PBIX: 2025 год совпал до рубля (vol 1 975 518, rev 55 485 520,78,
-- cost 27 881 160,62), январь-август 2026 — до рубля плюс-минус копейки.
CREATE TABLE IF NOT EXISTS cost_ready_goods (
    -- Первое число месяца документа поступления.
    month        DATE        NOT NULL,
    -- Документ поступления (Gpartner.dbo.prix_modeli.DOC_MODELI): id документа
    -- строкой — в источнике это numeric, а в PB-таблицах такого ключа нет.
    doc_modeli   TEXT        NOT NULL,
    model        TEXT        NOT NULL,
    articul      TEXT        NOT NULL,
    model_name   TEXT,
    -- Иерархия из Checks.dbo.Groups по MODEL_ID — см. «КЛАССИФИКАЦИЯ» выше.
    level01      TEXT,
    level02      TEXT,
    level03      TEXT,
    level04      TEXT,
    level05      TEXT,
    -- Страна производства из s_modeli.COUNTRY («Китай», «Узбекистан»…).
    country      TEXT,
    vol          NUMERIC     NOT NULL,
    -- Закупка без НДС, BYN (SUMMA_DOC - SUMMA_NDS).
    cost_byn     NUMERIC     NOT NULL,
    -- Выручка по учётной цене, BYN (KOL * sm.PRICE_UCH).
    rev_byn      NUMERIC     NOT NULL,
    -- № плана закупки: doc_modeli.OSN_ID → zak_tovar.PLAN_ID, плюс
    -- искусственная таблица планов ГП из olap.Procurement (та же связка, что в
    -- M-запросе PBIX). NULL — плана нет.
    plan_id      INTEGER,
    -- Закупщик из plan_proizv.PURCH_MANAGER. В дашборде он играет роль
    -- бренд-менеджера (колонка «Бренд-менеджер» у ГП-строк).
    purch_manager TEXT,
    synced_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (month, doc_modeli, model, articul)
);

COMMENT ON TABLE cost_ready_goods IS
    'Сторонняя готовая продукция: Gpartner.dbo.prix_modeli, операция '
    '«Поступление товара», STATUS = 0 (без Я-импорт/Тара/Упаковка/Косметика). '
    'Блок «Поступление товара стороннего» отчёта Power BI «Маржа выпуска'
    'Трикотаж». Синхронизируется sync_ready_goods() при обновлении кэша; '
    'дашборд маржи подмешивает её при gp=all|gp.';
COMMENT ON COLUMN cost_ready_goods.month IS
    'Первое число месяца даты документа поступления (в PBIX — EOMONTH: метка '
    'месяца, чтобы динамика складывалась с выпуском).';
COMMENT ON COLUMN cost_ready_goods.cost_byn IS
    'Закупка без НДС (SUMMA_DOC - SUMMA_NDS). Это НЕ расчётная себестоимость: '
    'у покупного товара нет норм и минут пошива.';
COMMENT ON COLUMN cost_ready_goods.rev_byn IS
    'Выручка по учётной цене (KOL * s_modeli.PRICE_UCH), BYN.';
COMMENT ON COLUMN cost_ready_goods.plan_id IS
    '№ плана закупки (zak_tovar / olap.Procurement.dbo.doc_mod_gp_hystory). '
    'NULL — поступление без плана.';
COMMENT ON COLUMN cost_ready_goods.level01 IS
    'Level 01…05 — из Checks.dbo.Groups по MODEL_ID (в PBIX те же group1…group6). '
    'Не из витрины выпуска: покупной товар в ней отсутствует.';

-- Дашборд режет таблицу по месяцу и джойнит к витрине по модели+артикулу
-- (Level 01…05 берутся из классификации выпуска).
CREATE INDEX IF NOT EXISTS cost_ready_goods_month_idx ON cost_ready_goods (month);
CREATE INDEX IF NOT EXISTS cost_ready_goods_model_idx ON cost_ready_goods (model, articul);
