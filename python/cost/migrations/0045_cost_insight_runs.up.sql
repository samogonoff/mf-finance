-- 0045 — журнал разборов блоков графиков языковой моделью («Разбор ИИ»)
--
-- Под логическими секциями страниц раздела («Маржа выпуска», «Норматив против
-- факта», «Динамика цен») появился блок с наблюдениями, которые пишет LLM по
-- ПОСЧИТАННЫМ на бэкенде фактам (см. app/insights.py). Эта таблица закрывает
-- две задачи одной записью.
--
-- 1. КЭШ. Один и тот же блок на тех же данных даёт тот же ответ, а вызов модели
--    стоит денег и 10–40 секунд ожидания. Ключ — request_hash: sha256 от блока,
--    контекста среза, всех серий графиков И имени модели. Смена модели или любой
--    цифры в графике меняет хеш, поэтому устаревший разбор показан быть не может
--    и TTL не нужен. Данные кэша обновляются раз в 3 часа (cache_worker), так что
--    попадание в кэш — обычное дело в пределах одной рабочей сессии.
--
-- 2. АУДИТ. Кто какой блок разбирал, какой моделью, сколько это стоило и что
--    ответило. Нужно и для разбора жалоб «мне показало не то» (видно точный
--    текст наблюдений и посчитанные факты, на которых он построен), и чтобы
--    видеть реальные затраты на модель, и чтобы по журналу решать, какие блоки
--    людям вообще интересны.
--
-- Пишутся ВСЕ запуски, включая неудачные (degraded=TRUE): их доля показывает,
-- насколько надёжен провайдер модели, а без записи это видно только в ELK.
-- Ответы из кэша новую строку НЕ создают — иначе журнал перестаёт отражать
-- фактические обращения к модели и затраты.

CREATE TABLE IF NOT EXISTS cost_insight_runs (
    id                BIGSERIAL   PRIMARY KEY,
    -- sha256(block + block_title + context + charts + model), см. insights.request_hash
    request_hash      TEXT        NOT NULL,
    -- Машинный ключ секции ('margin_output', 'norm_vs_fact', ...) и её заголовок
    -- как он показан пользователю: ключ для группировки, заголовок для чтения
    -- журнала человеком без залезания в код фронта.
    block             TEXT        NOT NULL,
    block_title       TEXT        NOT NULL DEFAULT '',
    email             TEXT        NOT NULL,
    model             TEXT        NOT NULL DEFAULT '',
    -- Наблюдения модели: [{"text": "...", "kind": "risk", "numbers_ok": true,
    --                      "unverified_numbers": []}]
    observations      JSONB       NOT NULL DEFAULT '[]'::jsonb,
    -- Факты, посчитанные кодом. Хранятся вместе с ответом: без них нельзя
    -- проверить, на чём именно модель построила вывод.
    facts             JSONB       NOT NULL DEFAULT '[]'::jsonb,
    -- Контекст среза (период, валюта, фильтры) — чтобы понимать, что человек
    -- видел на экране в момент разбора.
    context           JSONB       NOT NULL DEFAULT '{}'::jsonb,
    degraded          BOOLEAN     NOT NULL DEFAULT FALSE,
    error             TEXT        NOT NULL DEFAULT '',
    prompt_tokens     INTEGER,
    completion_tokens INTEGER,
    -- Стоимость приходит от провайдера строкой ('0.00001940') и хранится как
    -- есть: у разных провайдеров разная точность, а арифметику по деньгам мы
    -- тут не ведём.
    cost              TEXT        NOT NULL DEFAULT '',
    elapsed_ms        INTEGER,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Кэш: последний УСПЕШНЫЙ разбор по хешу. Частичный индекс — неудачные запуски
-- в кэш попадать не должны, иначе одна ошибка провайдера залипнет навсегда.
CREATE INDEX IF NOT EXISTS cost_insight_runs_cache_idx
    ON cost_insight_runs (request_hash, created_at DESC)
    WHERE degraded = FALSE;

-- Журнал: «что разбирали за последнюю неделю», «сколько потратили».
CREATE INDEX IF NOT EXISTS cost_insight_runs_created_idx
    ON cost_insight_runs (created_at DESC);

COMMENT ON TABLE cost_insight_runs IS
    'Журнал и кэш разборов блоков графиков языковой моделью («Разбор ИИ»). Ключ кэша request_hash включает модель и все данные графиков, поэтому TTL не нужен. Ответы из кэша строк не создают.';

-- Право на разбор. Пока — только тем, кто и так видит все цифры раздела:
-- разбор уходит во внешнюю модель (см. COST_LLM_* в .env.example), и первыми
-- его должны опробовать администраторы и ПЭО, а не бренд-менеджеры. Расширить
-- список — отдельным решением, когда станет ясно, что наблюдения не врут.
UPDATE cost_roles
   SET permissions = permissions || '["cost:insights"]'::jsonb
 WHERE name IN ('ПЭО', 'Full Admin')
   AND NOT permissions @> '["cost:insights"]'::jsonb;
