-- Откат витрины калькуляций и колонки объёма выпуска.
--
-- Витрина производна от cost_data_cache — её удаление данных не теряет,
-- пересоздаётся накатом 0036 заново.
--
-- Колонку «выпуск шт» тоже снимаем: она наполняется из источника при refresh
-- кэша, так что откат и повторный накат восстановят её содержимое. Но помните,
-- что до следующего refresh она будет пустой.

DROP MATERIALIZED VIEW IF EXISTS cost_calc_mv;

ALTER TABLE cost_data_cache
    DROP COLUMN IF EXISTS "выпуск шт";
