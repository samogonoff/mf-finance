-- 0048 — диалог в углублённом исследовании
--
-- До сих пор каждый вопрос к `/insights/ask` был самостоятельным
-- исследованием: агент получал вопрос и срез дашборда, но не знал, о чём уже
-- спрашивали. Уточняющий вопрос («а почему именно в этой подгруппе?») терял
-- контекст и начинался с нуля — на тесте 02.09.2026 это выглядело так, будто
-- сервис не умеет разговаривать.
--
-- Теперь исследования связываются в ветку: thread_id общий для всей переписки,
-- seq — номер раунда внутри неё. Новый вопрос без thread_id открывает ветку.
--
-- ЧТО ПОПАДАЕТ В КОНТЕКСТ СЛЕДУЮЩЕГО РАУНДА
-- =========================================
-- Не полная переписка с выгрузками инструментов, а сводка: вопрос, вывод и
-- трасса вызовов. Причины две. Сырые результаты прошлых шагов — это десятки
-- килобайт, и к третьему раунду промпт упирался бы в контекст модели. И они
-- УСТАРЕВШИЕ: витрина обновляется раз в три часа, а вывод по старым числам,
-- поданный как свежий, хуже отсутствия контекста. Нужны те же данные — агент
-- вызовет инструмент заново, это 1–3 секунды.
--
-- Кэш остаётся по-раундовым: request_hash уже включает вопрос, срез, модель и
-- метку обновления витрины, а теперь ещё и ветку — иначе одинаковый уточняющий
-- вопрос в двух разных ветках («а почему?») отдавал бы чужой ответ.

ALTER TABLE cost_insight_questions
    ADD COLUMN IF NOT EXISTS thread_id UUID,
    ADD COLUMN IF NOT EXISTS seq       INTEGER NOT NULL DEFAULT 1;

-- Существующие исследования (0046, 0047) — одиночные: каждое становится веткой
-- из одного раунда. Так они остаются читаемыми в журнале и не мешают новым.
UPDATE cost_insight_questions
   SET thread_id = job_id
 WHERE thread_id IS NULL;

ALTER TABLE cost_insight_questions
    ALTER COLUMN thread_id SET NOT NULL;

-- Сборка контекста ветки: «дай предыдущие раунды по порядку». Читается на каждый
-- уточняющий вопрос, поэтому индекс, а не сканирование журнала.
CREATE INDEX IF NOT EXISTS cost_insight_questions_thread_idx
    ON cost_insight_questions (thread_id, seq);

COMMENT ON COLUMN cost_insight_questions.thread_id IS
    'Ветка диалога. Вопрос без thread_id открывает новую; уточняющий продолжает существующую, и агент получает сводку прошлых раундов (вопрос + вывод + трасса), а не их сырые данные — те устаревают вместе с витриной.';

COMMENT ON COLUMN cost_insight_questions.seq IS
    'Номер раунда внутри ветки, начиная с 1.';
