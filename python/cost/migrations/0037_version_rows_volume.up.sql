-- Колонка «выпуск шт» в строках версий калькуляций.
--
-- ПОЧЕМУ ЭТО НУЖНО
-- ================
-- Миграция 0036 добавила «выпуск шт» в cost_data_cache и в CACHE_COLUMNS
-- (app/db.py). Но CACHE_COLUMNS — это ещё и список колонок cost_calc_version_rows:
-- версия калькуляции хранит построчный снимок кэша, и код гоняет данные между
-- таблицами одним и тем же списком (_ensure_original_version, create_version,
-- _apply_version_rows_to_cache).
--
-- Из-за пропущенной колонки обновление кэша 13.08.2026 упало на переприменении
-- версий:
--   asyncpg.exceptions.UndefinedColumnError: column "выпуск шт" does not exist
--   DETAIL: There is a column named "выпуск шт" in table "cost_data_cache",
--           but it cannot be referenced from this part of the query.
-- (INSERT INTO cost_data_cache (...) SELECT ... FROM cost_calc_version_rows)
--
-- Вся загрузка идёт одной транзакцией, поэтому откатилось ВСЁ: кэш остался
-- прежним, «выпуск шт» пустым, и дашборд не мог показать показатели выпуска.
--
-- ПОЧЕМУ КОЛОНКУ НАДО ИМЕННО ДОБАВИТЬ, А НЕ ИСКЛЮЧИТЬ ИЗ ЗАПРОСА
-- ==============================================================
-- _apply_version_rows_to_cache удаляет строки ключа из кэша и вставляет вместо
-- них строки версии. Если версия не несёт объём выпуска, то у калькуляций с
-- согласованными версиями он после каждого refresh обнулялся бы — молча и
-- именно там, где цены уже правили руками.
--
-- cost_price_pending трогать не нужно: у него собственный список колонок
-- (_PENDING_CACHE_COLS в app/db.py), объёма выпуска там нет и не требуется.
--
-- ПОПУТНО ЗАКРЫТ ВОПРОС ИЗ 0036: max("выпуск шт") — верная свёртка
-- ==============================================================
-- В 0036 стояло «ПРОВЕРИТЬ на первых реальных данных». Проверено 14.08.2026 на
-- 87 184 ключах после первого успешного refresh: объём лежит НЕ на каждой строке
-- калькуляции. У 696 ключей (0,8%) внутри ключа два разных значения, и картина
-- всегда одна — на строках материалов и операций стоит 0, а реальный тираж несёт
-- одна строка (тип «себестоимость лиса вязание»):
--   1040PA-1414 / 251040PAN / Ч24.11.3231 → 13 строк с 0 и 2 строки с 4800
-- max() берёт именно её. sum() завысил бы объём, avg() занизил.
--
-- Заполнено 55 449 ключей из 87 184 (64%): у остальных в источнике нули или
-- пусто. Итого 65,9 млн штук по ФКСС.

ALTER TABLE cost_calc_version_rows
    ADD COLUMN IF NOT EXISTS "выпуск шт" NUMERIC;

COMMENT ON COLUMN cost_calc_version_rows."выпуск шт" IS
    'Объём выпуска, штук. Копируется из cost_data_cache вместе с остальным '
    'снимком калькуляции и возвращается в кэш при применении версии.';
