-- 0041 — настройки таблицы на пользователя (видимость, порядок и ширины колонок)
--
-- Пожелания № 9 и № 14 из «Списка доработок»: пользователь настраивает таблицу
-- под себя, и настройка должна жить — переживать обновление страницы, новый вход
-- и смену устройства.
--
-- До сих пор всё лежало только в localStorage браузера: cost_column_visibility,
-- cost_sticky_col_widths, cost_page_size, cost_filters_open, cost_hide_dwh_sent.
-- Это значит, что настройка терялась при входе с другого компьютера или в другом
-- браузере, а в приватном режиме — сразу. Теперь она хранится на сервере и
-- привязана к пользователю; localStorage остаётся быстрым кэшем, чтобы таблица
-- отрисовывалась настроенной ещё до ответа сервера.
--
-- Формат хранения — JSONB одним документом, а не колонка на каждую настройку.
-- Причина: состав настроек меняется вместе с интерфейсом (сегодня видимость и
-- ширины, завтра порядок колонок и закрепление), и каждая новая настройка не
-- должна требовать миграции. Схему документа держит фронт, сервер её не
-- валидирует по полям — только ограничивает размер (см. app/routes.py).

CREATE TABLE IF NOT EXISTS cost_user_table_prefs (
    email       TEXT PRIMARY KEY,
    -- {"columns": {"visibility": {...}, "order": [...], "widths": {...}}, "pageSize": 25, ...}
    prefs       JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE cost_user_table_prefs IS
    'Настройки главной таблицы раздела «Себестоимость» на пользователя: видимость, порядок и ширины колонок. Документ JSONB, схему держит фронт.';
