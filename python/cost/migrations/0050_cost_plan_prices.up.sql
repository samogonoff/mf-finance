-- Плановая себестоимость единицы из справочника моделей Лисы.
--
-- ЗАЧЕМ
-- =====
-- Заказчик (Апанасенок О.А., 25.08.2026): дашборд маржи выпуска должен получить
-- отдельный лист с отклонениями ПО АРТИКУЛАМ — фактической себестоимости от
-- ПЛАНОВОЙ, плюс номер плана. Это страница «Отклонение сс» отчёта Power BI
-- «Маржа выпуска Трикотаж», которую при первом переносе (docs/bi/pbi-margin-port.md)
-- пришлось пометить как непереносимую: плановой себестоимости в нашем источнике
-- [Checks].[dbo].[CostHistory] нет — там только норма расхода материала.
--
-- Разбор M-запроса .pbix показал источник: колонка PLAN_PRICE справочника
-- Gpartner.dbo.S_MODELI, переименованная в отчёте в «План. себ-ть, руб.».
-- Сверено по артикулам со скриншота заказчика — совпадает до копейки
-- (25-40508П-1 → 10,80; 25-40509П-1 → 11,09; 25-5505Ц-2 → 14,47).
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА КЭША
-- ===========================================
-- Плановая цена живёт на МОДЕЛИ (справочник), а не на строке калькуляции: одно
-- значение на пару модель+артикул независимо от задания, плана и даты расчёта.
-- Колонкой кэша она копировалась бы в каждую из ~1 млн строк, а менялась бы
-- только вместе с полным обновлением кэша (25 минут). Справочник синхронизируется
-- за секунды и независимо.
--
-- В витрину cost_calc_mv тоже НЕ кладём: витрина — свёртка кэша, и добавление
-- туда внешнего справочника означало бы пересоздание MV при каждом изменении
-- плановых цен. Запросы дашборда джойнят справочник сами (LEFT JOIN по
-- model+articul), это дешёво — записей тысячи, не миллионы.
--
-- ПОКРЫТИЕ
-- ========
-- Все 6 426 пар модель+артикул выпуска 2026 года нашлись в справочнике, но
-- ненулевая плановая цена только у 3 895 (61%): у остальных PLAN_PRICE = 0, то
-- есть план не заведён. Ноль ≠ «плановая себестоимость нулевая», поэтому при
-- синхронизации он пишется как NULL, а доля строк с планом отдаётся в интерфейс
-- рядом с отклонением — иначе «отклонение по 61% выпуска» читалось бы как по
-- всему.
CREATE TABLE IF NOT EXISTS cost_plan_prices (
    model      TEXT        NOT NULL,
    articul    TEXT        NOT NULL,
    -- Плановая себестоимость ЕДИНИЦЫ, BYN. NULL — план не заведён (в источнике 0).
    plan_price NUMERIC,
    synced_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (model, articul)
);

COMMENT ON TABLE cost_plan_prices IS
    'Плановая себестоимость единицы из Gpartner.dbo.S_MODELI (PLAN_PRICE). '
    'Синхронизируется sync_plan_prices() при обновлении кэша. Нужна для листа '
    '«Отклонения по артикулам» дашборда маржи выпуска.';
COMMENT ON COLUMN cost_plan_prices.plan_price IS
    'BYN за единицу. NULL — план не заведён (в источнике 0). Не путать с '
    'нормативной себестоимостью (cost_calc_mv.cost_byn) и фактической '
    '(cost_fact_byn, по фактической стоимости минуты).';

-- Дата последней успешной синхронизации — чтобы интерфейс мог показать
-- свежесть плановых цен отдельно от свежести кэша: они обновляются разными
-- процессами и расходятся.
CREATE INDEX IF NOT EXISTS cost_plan_prices_synced_idx ON cost_plan_prices (synced_at);
