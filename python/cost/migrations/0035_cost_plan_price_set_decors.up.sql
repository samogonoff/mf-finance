-- 0035 — декоры в наборах цен по плану.
--
-- Набор цен теперь держит два вида строк: материалы и декоры. Они устроены
-- ПО-РАЗНОМУ, и это принципиально:
--
--   Материал — есть Норма и «цена материала», стоимость статьи считается как
--   Норма × цена × коэффициент (см. миграцию 0031). Ключ — пять полей:
--   Наименование, артикул материала, свойство1..3.
--
--   Декор — Нормы и цены материала НЕТ вообще (проверено: у всех 1208 строк
--   декоров под КПСС оба поля пустые), стоимость лежит прямо в «Декоры, руб.»
--   и «Декоры, USD.». Идентифицируется отдельным полем «Декоры, наименование»
--   (обычное «Наименование» у декоров пустое). Поэтому «цена декора» — это
--   сама сумма, и корректировка проставляется в неё напрямую, без нормы и
--   коэффициента.
--
-- Ключ декора проверен на живых данных: 159 групп (план + наименование декора)
-- на 83 плана, и у ВСЕХ ровно одна цена — разброса нет вообще (у материалов
-- он есть у 1.3% групп). Строк с суммой, но без наименования, — ноль, то есть
-- ключ покрывает 100% тарифицированных декоров.
--
-- row_kind входит в уникальный ключ: без него материал и декор с одинаковым
-- наименованием в одном наборе конфликтовали бы. Наименование декора кладём в
-- колонку "Наименование" (у декоров она в источнике пустая), остальные четыре
-- поля ключа остаются пустыми.

ALTER TABLE cost_plan_price_set_rows
    ADD COLUMN IF NOT EXISTS row_kind text NOT NULL DEFAULT 'material';

-- Имя прежнего ограничения PostgreSQL сгенерировал сам и усёк до 63 байт —
-- берём его как есть, из pg_constraint.
ALTER TABLE cost_plan_price_set_rows
    DROP CONSTRAINT IF EXISTS "cost_plan_price_set_rows_set_id_Наименование_а_key";

ALTER TABLE cost_plan_price_set_rows
    ADD CONSTRAINT cost_plan_price_set_rows_kind_key
        UNIQUE (set_id, row_kind, "Наименование", "артикул материала",
                "свойство1", "свойство2", "свойство3");

ALTER TABLE cost_plan_price_set_rows
    ADD CONSTRAINT cost_plan_price_set_rows_kind_check
        CHECK (row_kind IN ('material', 'decor'));
