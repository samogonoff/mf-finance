def matching_rule(ctry: str | None, direction: str | None = None,
                  group_cfo1: str | None = None) -> tuple:
    """(ключ правила, имя цели) для ячейки по явному приоритету уровней:
    направление → группа ЦФО → страна без сужения → вся ГК. Ключ —
    (страна правила, уровень сработавшего матчера "dir"/"g1"/None, значение);
    внутри уровня правила перебираются в порядке объявления."""
    for kind, value in (("dir", direction or ""), ("g1", group_cfo1 or "")):
        if not value:
            continue
        for row in DEN_RULES:
            if row[0] is not None and row[0] != (ctry or ""):
                continue
            if (kind, value) in row[1]:
                return (row[0], kind, value), row[2]
    for row in DEN_RULES:
        if row[1] or row[0] is None:
            continue
        if row[0] == (ctry or ""):
            return (row[0], None, None), row[2]
    return (None, None, None), "grp"


def resolve(ctry: str | None, direction: str | None = None,
            group_cfo1: str | None = None,
            fallback: tuple | None = None) -> tuple:
    """Цель знаменателя для (страна, направление, группа ЦФО) — кортеж
    предикатов над ячейкой den_grain (см. TARGETS).

    fallback (p14 при активном фильтре «Направление»): если ячейка попала не
    на канальное правило, а на уровень страны/ГК, вместо него возвращается
    fallback — объединение целей выбранных направлений (narrowed)."""
    key, name = matching_rule(ctry, direction, group_cfo1)
    if fallback is not None and key[1] is None:
        return fallback
    return TARGETS[name]


def country_target(ctry: str | None) -> tuple:
    """Цель уровня страны: вся выручка страны; None, смесь стран или код
    вне отчётных четырёх — вся выручка ГК (инвариант «смешанные страны без
    направления → ГК»)."""
    return TARGETS[COUNTRY_TARGETS.get(ctry or "", "grp")]


def validate(known_values: dict) -> list[str]:
    """Проблемы правил против фактических DISTINCT витрины (ключи
    countries / directions / groups / channels); пустой список = ок. Ловит
    опечатки в правилах (значения вне витрины), цели и уровни вне допустимых,
    страны без покрывающего правила и страны, чей фолбэк уводит в ГК."""
    problems: list[str] = []
    countries = set(known_values.get("countries") or [])
    dims = {"dir": set(known_values.get("directions") or []),
            "g1": set(known_values.get("groups") or [])}
    channels = set(known_values.get("channels") or [])
    kinds = {"dir", "g1"}
    for row in DEN_RULES:
        ctry, matchers, name = row[0], row[1], row[2]
        if name not in TARGETS:
            problems.append("правило %r: цель %r вне TARGETS" % ((ctry, matchers), name))
        if ctry is not None and countries and ctry not in countries:
            problems.append("правило %r: страны нет в витрине" % ((ctry, matchers),))
        for kind, value in matchers:
            if kind not in kinds:
                problems.append("правило %r: неизвестный уровень %r"
                                % ((ctry, matchers), kind))
            elif dims[kind] and value not in dims[kind]:
                problems.append("правило %r: значения %r нет в витрине (%s)"
                                % ((ctry, matchers), value, kind))
    # предикаты целей должны опираться на существующие измерения
    for name, preds in TARGETS.items():
        for pred in preds:
            if "ctry" in pred and countries and pred["ctry"] not in countries:
                problems.append("цель %r: страны %r нет в витрине" % (name, pred["ctry"]))
            if "chan" in pred and channels and pred["chan"] not in channels:
                problems.append("цель %r: канала %r нет в витрине" % (name, pred["chan"]))
            if "dir" in pred and dims["dir"] and pred["dir"] not in dims["dir"]:
                problems.append("цель %r: направления %r нет в витрине"
                                % (name, pred["dir"]))
    if countries:
        # страны вне отчётных четырёх (TR, CN и прочие) правил не имеют by
        # design — их ячейки fallback-ом уходят в ГК
        for ctry in sorted(countries & set(COUNTRY_TARGETS)):
            if not any(row[0] == ctry for row in DEN_RULES):
                problems.append("страна %r без правила (фолбэк уводит в ГК)" % ctry)
    return problems


def methodology_text() -> str:
    """Абзац методологии о знаменателе долей (вставляется в
    METHODOLOGY_P10/P11/P14/B1): уровни + таблица правил, генерируется из
    DEN_RULES — текст не расходится с данными."""
    parts = [
        "Знаменатель доли ФОТ — «Продажи без НДС» P&L по правилу "
        "«страна × направление → канал»: ГК — вся выручка группы; строка "
        "уровня страны, карточка страны или страна в фильтре — вся выручка "
        "страны (для BY и RU тоже — ранее вся ГК); строка с направлением или "
        "группой ЦФО (и фильтры Направление/Группа/Подгруппа/ЦФО у карточек) — "
        "объединение целей правил ячеек строки, сумма ячеек без двойного "
        "счёта; срез ЦФО и юрлица знаменатель не сужают, ВГО сужает. Правила:"
    ]
    last_ctry = None
    for ctry, matchers, name, _quote in DEN_RULES:
        if ctry is None:
            continue
        if ctry != last_ctry:
            parts.append("%s:" % ctry)
            last_ctry = ctry
        dim = ", ".join("%s «%s»" % (k, v) for k, v in
                        sorted(matchers)) if matchers else "без сужения"
        parts.append("%s → %s;" % (dim, TARGET_LABELS[name]))
    parts.append(
        "смеси стран и строки без страны — вся выручка ГК. Интерпретации: "
        "«Производство ∩ RU» — выручка направления «Производство Ногинск» "
        "(площадка Ногинск); у UZ канала «Опт УЗ» нет — база направления "
        "«ОПТ УЗ» и базы «Отделов UZ» берутся ячейками выручки (продажи ОПТ "
        "УЗ сейчас лежат в канале «Розница UZ», «Полотно» даёт отрицательную "
        "выручку-сторно — вклад остаётся).")
    return " ".join(parts)
