"""Ошибки выгрузки «1:1 как в деке» (задача 663620).

Отдельный модуль, чтобы их могли поднимать и движок, и биндеры: пакет
`engine` импортирует `registry` → `binders`, поэтому обратный импорт
(биндер → engine) дал бы цикл.
"""

from __future__ import annotations


class AssetMismatch(RuntimeError):
    """Актив не соответствует манифесту (или актива/манифеста нет)."""


class EmptySlice(ValueError):
    """В выбранном срезе нет данных — отдавать нечего (роут отвечает 422)."""

    def __init__(self, tab: str) -> None:
        super().__init__(
            "fot_deck: в выбранном срезе нет данных по вкладке %r — свод пуст, "
            "стран с численностью нет; измените фильтры (год/полугодие, "
            "направление) и повторите выгрузку" % (tab,))
        self.tab = tab


__all__ = ["AssetMismatch", "EmptySlice"]
